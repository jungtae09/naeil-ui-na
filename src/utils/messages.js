/* ---------------- 선택 로직 ---------------- */

function pick(list, seed) {
  if (!list || list.length === 0) return ''
  return list[Math.abs(seed) % list.length]
}

/** 문자열 → 안정적인 정수 (같은 날엔 같은 문장이 나오도록) */
function hash(str) {
  let h = 0
  for (let i = 0; i < str.length; i++) {
    h = (h << 5) - h + str.charCodeAt(i)
    h |= 0
  }
  return h
}

/** 체크할 때마다 랜덤 */
export function randomCheckMessage() {
  return CHECK_MESSAGES[Math.floor(Math.random() * CHECK_MESSAGES.length)]
}

export function randomCompleteMessage() {
  return COMPLETE_MESSAGES[Math.floor(Math.random() * COMPLETE_MESSAGES.length)]
}

/**
 * 상황에 맞는 '오늘의 한마디'.
 * 같은 날 같은 상황이면 같은 문장이 나온다.
 */
export function quoteOfTheDay({ ymd, streak = 0, isComplete = false, hadBreak = false, totalDays = 0 }) {
  let category = 'habit'
  // 기록이 한 줄도 없을 때만 '첫날' 문구를 쓴다.
  // (<= 1 로 두면 둘째 날 아침에도 첫날 문구가 다시 떴다)
  if (totalDays === 0) category = 'first'
  else if (hadBreak && streak === 0) category = 'restart'
  else if (isComplete) category = 'growth'
  else if (streak >= 7) category = 'habit'
  else if (streak === 0) category = 'encourage'
  else category = ['habit', 'growth', 'reflect', 'fact'][Math.abs(hash(ymd)) % 4]

  const list = QUOTES[category] ?? QUOTES.habit
  return { text: pick(list, hash(ymd + category)), category }
}

export function questionOfTheDay(ymd) {
  return pick(DAILY_QUESTIONS, hash('q' + ymd))
}

